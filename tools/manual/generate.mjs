// Brings the manual (public/tutorials/<lang>) up to date with the editor:
//
//   npm run manual              icons, screenshots and check
//   npm run manual -- icons     icons.js, from src/editor/icons.ts and tools.ts
//   npm run manual -- shots     the screenshots of shots.mjs
//   npm run manual -- check     what the pages name that the editor lacks, and
//                               the reverse
//
// DocGeo is served by Vite and driven by Playwright, the modules of the
// editor being read in the page itself.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { format } from "prettier";
import { createServer } from "vite";
import { SHOTS } from "./shots.mjs";

const LANG = "fr";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const MANUAL = join(ROOT, "public/tutorials", LANG);
const VIEWPORT = { width: 1200, height: 720 };
const QUALITY = 0.8;

const tasks = process.argv.slice(2);
const wanted = (task) => !tasks.length || tasks.includes(task);

const server = await createServer({
    root: ROOT,
    logLevel: "error",
    server: { port: 5190, strictPort: false, host: "127.0.0.1" },
});
await server.listen();
const base = server.resolvedUrls.local[0];
const browser = await chromium.launch();
let failed = false;

try {
    const editor = await open("editor.html");
    const data = await editor.evaluate(async () => {
        const tools = await import("/src/editor/tools.ts");
        const { message } = await import("/src/editor/messages.ts");
        const catalog = await import("/src/editor/catalog.ts");
        const { ACTION_ICONS } = await import("/src/editor/icons.ts");
        return {
            actions: ACTION_ICONS,
            families: tools.TOOL_FAMILIES.map((family) => ({
                name: message(family.name),
                hue: family.hue,
                tone: family.tone,
                items: family.items.map((item) => ({
                    label: tools.itemLabel(item),
                    icon: item.tools[0].icon,
                })),
            })),
            commands: catalog.COMMANDS.map(catalog.commandName),
        };
    });
    await editor.close();

    if (wanted("icons")) await writeIcons(data);
    if (wanted("shots")) for (const shot of SHOTS) await capture(shot);
    if (wanted("check")) check(data);
} finally {
    await browser.close();
    await server.close();
}
process.exitCode = failed ? 1 : 0;

async function open(path) {
    const page = await browser.newPage({ viewport: VIEWPORT });
    const separator = path.includes("?") ? "&" : "?";
    await page.goto(`${base}${path}${separator}lang=${LANG}`);
    await page.waitForLoadState("networkidle");
    await page.waitForTimeout(800);
    return page;
}

async function writeIcons({ actions, families }) {
    const tools = Object.fromEntries(
        families.flatMap(({ hue, tone, items }) =>
            items.map(({ label, icon }) => [label, [hue, tone, icon]]),
        ),
    );
    const source =
        "// Generated by tools/manual/generate.mjs from the editor's icons: do not edit.\n" +
        `window.DG_ICONS = ${JSON.stringify({ actions, tools })};\n`;
    const file = join(MANUAL, "icons.js");
    writeFileSync(file, await format(source, { filepath: file, tabWidth: 4 }));
    console.log(
        "icons.js:",
        Object.keys(tools).length,
        "tools,",
        Object.keys(actions).length,
        "actions",
    );
}

// The helpers a shot's run receives.
function helpers(page) {
    const evaluate = (fn, arg) => page.evaluate(fn, arg);
    // Where an object is in the window.
    const point = (name) =>
        evaluate(async (name) => {
            const { studio } = await import("/src/editor/main.ts");
            const scene = studio.scene;
            const [x, y] = scene.getObj(name).screen;
            const box = scene.svg.dom().getBoundingClientRect();
            return [box.left + x, box.top + y];
        }, name);
    // A point of an object's drawing.
    const on = (name) =>
        evaluate(async (name) => {
            const { studio } = await import("/src/editor/main.ts");
            const view = studio.scene.getObj(name).dom.dom();
            const shape = view.matches("path, circle, line, polygon")
                ? view
                : view.querySelector("path, circle, line, polygon");
            const local =
                shape.tagName === "circle"
                    ? new DOMPoint(
                          shape.cx.baseVal.value + shape.r.baseVal.value,
                          shape.cy.baseVal.value,
                      )
                    : shape.getPointAtLength(shape.getTotalLength() * 0.3);
            const { x, y } = local.matrixTransform(shape.getScreenCTM());
            return [x, y];
        }, name);
    const t = (key) =>
        evaluate(
            async (key) =>
                (await import("/src/editor/messages.ts")).message(key),
            key,
        );
    const command = (name) =>
        evaluate(async (name) => {
            const catalog = await import("/src/editor/catalog.ts");
            return catalog.commandName(
                catalog.COMMANDS.find((c) => c.name === name),
            );
        }, name);
    const button = async (key) =>
        page
            .locator(`button[aria-label="${await t(key)}"]`)
            .first()
            .click();
    const type = async (lines) => {
        for (const line of lines) {
            await page.fill(".dge-input", line);
            await page.press(".dge-input", "Enter");
            await page.waitForTimeout(150);
        }
        await page.locator(".dge-input").blur();
    };
    return { page, point, on, t, command, button, type };
}

async function capture({ file, page: path, clip, run }) {
    const page = await open(path);
    try {
        await run?.(helpers(page));
        await page.waitForTimeout(500);
        const png = await page.screenshot({ clip });
        writeFileSync(join(MANUAL, "img", file), await webp(png));
        console.log("img/" + file);
    } catch (error) {
        failed = true;
        console.error(`img/${file}: ${error.message}`);
    } finally {
        await page.close();
    }
}

// Chromium encodes WebP itself: no image tool to install.
async function webp(png) {
    const page = await browser.newPage();
    const url = await page.evaluate(
        async ([source, quality]) => {
            const image = new Image();
            image.src = source;
            await image.decode();
            const canvas = document.createElement("canvas");
            canvas.width = image.naturalWidth;
            canvas.height = image.naturalHeight;
            canvas.getContext("2d").drawImage(image, 0, 0);
            return canvas.toDataURL("image/webp", quality);
        },
        ["data:image/png;base64," + png.toString("base64"), QUALITY],
    );
    await page.close();
    return Buffer.from(url.split(",")[1], "base64");
}

// The manual's icons, tools and commands against the editor's.
function check({ actions, families, commands }) {
    const pages = readdirSync(MANUAL).filter((file) => file.endsWith(".html"));
    const html = Object.fromEntries(
        pages.map((file) => [file, readFileSync(join(MANUAL, file), "utf8")]),
    );
    const labels = new Set(
        families.flatMap(({ items }) => items.map(({ label }) => label)),
    );
    const problems = [];
    for (const [file, text] of Object.entries(html)) {
        for (const [, name] of text.matchAll(/data-i="([^"]*)"/g))
            if (!(name in actions))
                problems.push(`${file}: no action icon "${name}"`);
        for (const [, label] of text.matchAll(/data-t="([^"]*)"/g))
            if (!labels.has(label))
                problems.push(`${file}: no tool "${label}"`);
        for (const [, image] of text.matchAll(/src="img\/([^"]*)"/g))
            if (!SHOTS.some(({ file }) => file === image))
                problems.push(`${file}: img/${image} is not in shots.mjs`);
    }
    for (const { file } of SHOTS)
        if (!Object.values(html).some((text) => text.includes(`img/${file}`)))
            problems.push(`shots.mjs: img/${file} is used by no page`);
    for (const label of labels)
        if (!html["menu-outils.html"].includes(`data-t="${label}"`))
            problems.push(`menu-outils.html: tool "${label}" not described`);
    const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    for (const name of commands)
        if (
            !new RegExp(`<strong>\\s*${escape(name)}\\s*</strong\\s*>`).test(
                html["commandes.html"],
            )
        )
            problems.push(`commandes.html: command "${name}" not described`);
    if (problems.length) failed = true;
    console.log(
        problems.length
            ? problems.join("\n")
            : "check: the manual names every tool and command of the editor",
    );
}
