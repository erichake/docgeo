// On the line of the centers O and P of two circles c and d, where their
// radical axis cuts it.
const radical = (H, O, c, P, d) =>
    `${H} = Point(${O} + (1 + (${c}^2 - ${d}^2) / d(${O}, ${P})^2) / 2 * (${P} - ${O}))`;

// The touch points on two circles, of centers O1 and O2, of a common
// tangent: outer (one side) or inner (both sides), turned one way (1) or
// the other (-1).
const touches = (T, U, inner, turn) => {
    const angle = `${turn < 0 ? "-" : ""}acos((c1 ${inner ? "+" : "-"} c2) / D)`;
    return [
        `${T} = Point(var D = d(O1, O2); rotate(O1 + c1 * (O2 - O1) / D, O1, ${angle}))`,
        `${U} = Point(var D = d(O1, O2); rotate(O2 ${inner ? "-" : "+"} c2 * (O2 - O1) / D, O2, ${angle}))`,
    ];
};

