// The disk's message, the type's for the other initials.
const messages = (count) =>
    Object.fromEntries(
        LANGS.map((lang) => [lang, [DISK[lang], ...Array(count).fill("")]]),
    );

const DISK_LINES = ["O = (0, 0)", "Hz = Circle(O, 4)"];

const unit = (P) => `(${P} - O) / Hz`;
const figure = (z) => `O + Hz * (${z})`;
// φa(z) and its inverse.
const to = (a, z) => `((${z}) - ${a}) / (1 - conj(${a}) * (${z}))`;
const from = (a, w) => `((${w}) + ${a}) / (1 + conj(${a}) * (${w}))`;

// The ideal points p, beyond Y from X, and q, beyond X, of the geodesic
// through X and Y, inside the disk or on its edge, as the ends of an arc
// drawn by these macros; the variables' names end with `k`.
const ends = (X, Y, k = "") =>
    [
        `var s${k} = ${unit(X)}`,
        `var t${k} = ${unit(Y)}`,
        `var near${k} = mod(s${k}) <= mod(t${k})`,
        `var xa${k} = near${k} ? s${k} : t${k}`,
        `var ya${k} = near${k} ? t${k} : s${k}`,
        `var w${k} = ${to(`xa${k}`, `ya${k}`)}`,
        `var u${k} = w${k} / mod(w${k})`,
        `var ideal${k} = mod(xa${k}) > 1 - 1e-9`,
        `var py${k} = ideal${k} ? ya${k} : ${from(`xa${k}`, `u${k}`)}`,
        `var px${k} = ideal${k} ? xa${k} : ${from(`xa${k}`, `-u${k}`)}`,
        `var p${k} = near${k} ? py${k} : px${k}`,
        `var q${k} = near${k} ? px${k} : py${k}`,
    ].join("; ");

// Point V of an arc from X to Y, moved off the chord XY if on it.
const offChord = (V, X, Y) =>
    [
        `var ch = ${Y} - ${X}`,
        `var n = i * ch / mod(ch)`,
        `var h = dot(n, ${V} - ${X})`,
        `var lim = 1e-4 * mod(ch)`,
        `${V} + (abs(h) < lim ? ((h < 0 ? -1 : 1) * lim - h) * n : 0 * n)`,
    ].join("; ");

// The point of the geodesic of ideal points P and Q nearest to O, as the
// middle of its arc.
const middle = (P, Q) =>
    `var V = ${figure(
        `(${unit(P)} + ${unit(Q)}) / (2 + sqrt(4 - mod(${unit(P)} + ${unit(Q)})^2))`,
    )}; ${offChord("V", P, Q)}`;

// The hyperbolic midpoint `mid` of the points of the unit disk a and b.
const midpoint = (a, b) =>
    `var w = ${to(a, b)}; var m = w / (1 + sqrt(1 - mod(w)^2)); var mid = ${figure(from(a, "m"))}`;

// A geodesic of the figure, an arc from G1 to G2, its ends, and its
// center K.
const GEODESIC = (G1, G2, X, g, K) => [
    `${X} = Point(${middle(G1, G2)})`,
    `${g} = Arc(${G1}, ${X}, ${G2})`,
    `${K} = Center(${g})`,
];

// The ideal points p and q of a geodesic of the figure, an arc g of center
// K, where its circle meets the disk's edge; the variables' names end with
// `k`. Not the arc's ends: those of a final are inside its application,
// where opening a box can't reach them.
const ideal = (K, g, k = "") =>
    [
        `var kc${k} = ${unit(K)}`,
        `var mk${k} = mod(kc${k})`,
        `var rr${k} = ${g} / Hz`,
        `var p${k} = kc${k} / mk${k} * (1 + i * rr${k}) / mk${k}`,
        `var q${k} = kc${k} / mk${k} * (1 - i * rr${k}) / mk${k}`,
    ].join("; ");

const help = (...texts) => tr(...texts);

// The Euclidean center of the hyperbolic circle of center C and Euclidean
// radius rho in the unit disk where C is moved to 0: the middle of its
// diameter along OC.
const circleCenter = (rho) =>
    `var c = ${unit("C")}; var dir = mod(c) < 1e-12 ? 1 : c / mod(c); var x1 = (${rho}) * dir; var x2 = -x1; ${figure(`(${from("c", "x1")} + ${from("c", "x2")}) / 2`)}`;
// tanh(r / 2), r being the hyperbolic radius.
const RHO = "(exp(r) - 1) / (exp(r) + 1)";

