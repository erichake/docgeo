// Hyperbolic geometry in the Poincaré disk Hz, of center O, a fixed
// initial of every macro (see MACROS.md). The formulas work in the unit
// disk, z = (P - O) / Hz, where the Möbius map φa(z) = (z - a) / (1 - āz)
// takes a to 0 and keeps the disk: a geodesic through 0 is a diameter.
// A geodesic is drawn as the arc of a circle through three of its points;
// when it is a diameter, they are aligned, and the middle one is moved by
// 1/10000 of the arc's chord, which no eye sees.

